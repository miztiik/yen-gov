def _fowler_winner(rows: list[dict[str, str]]) -> dict[str, str]:
    """Apply the Fowler tiebreaker to pick the canonical row.

    Rule (docstring): shorter ``short`` wins; on tie, prefer the row
    without dashes or spaces in ``short``; on tie, prefer the row with
    more aliases / older-looking party_id (proxied as the row whose
    ``party_id`` sorts EARLIEST alphabetically, which favours older /
    shorter / less-suffixed ids).
    """
    def key(r: dict[str, str]) -> tuple[int, int, int, str]:
        short = (r.get("short") or "")
        aliases = [a for a in (r.get("aliases") or "").split("|") if a.strip()]
        has_dash_or_space = 1 if (" " in short or "-" in short) else 0
        return (
            len(short),
            has_dash_or_space,
            -len(aliases),
            r.get("party_id") or "",
        )
    return min(rows, key=key)


def _read_parties(path: Path) -> tuple[list[str], list[dict[str, str]]]:
    with path.open(encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        fieldnames = list(reader.fieldnames or [])
        rows = list(reader)
    return fieldnames, rows


def _write_csv(
    path: Path, fieldnames: list[str], rows: list[dict[str, str]]
) -> None:
    buf = io.StringIO(newline="")
    writer = csv.DictWriter(buf, fieldnames=fieldnames, lineterminator="\n")
    writer.writeheader()
    for row in rows:
        writer.writerow({k: row.get(k, "") for k in fieldnames})
    path.write_text(buf.getvalue(), encoding="utf-8", newline="")


def _merge_aliases(canonical: dict[str, str], duplicate: dict[str, str]) -> str:
    """Return the merged ``aliases`` cell for the canonical row.

    Union of canonical.aliases U duplicate.aliases U {duplicate.short};
    upper-cased dedupe, sorted lexicographically, pipe-joined. The
    duplicate's short is preserved as an alias so the resolver's existing
    alias-lookup path still resolves any publisher label that historically
    pointed to the duplicate's id.
    """
    merged: set[str] = set()
    for raw in (
        canonical.get("aliases") or "",
        duplicate.get("aliases") or "",
        duplicate.get("short") or "",
    ):
        for token in str(raw).split("|"):
            cleaned = token.strip()
            if cleaned:
                merged.add(cleaned)
    return "|".join(sorted(merged))


def _scan_collisions(
    rows: list[dict[str, str]],
) -> dict[str, list[dict[str, str]]]:
    """Group non-sentinel rows by upper-cased ``full`` and keep only sets
    of size > 1. Rows missing ``full`` are skipped (no collision possible).
    """
    by_full: dict[str, list[dict[str, str]]] = {}
    for r in rows:
        if (r.get("is_sentinel") or "").strip().lower() == "true":
            continue
        full = (r.get("full") or "").strip().upper()
        if not full:
            continue
        by_full.setdefault(full, []).append(r)
    return {f: rs for f, rs in by_full.items() if len(rs) > 1}


def _classify(
    full: str, members: list[dict[str, str]]
) -> tuple[str, str | None]:
    """Return (class_letter, note).

    Class A iff a ``(delete_pid, keep_pid)`` pair from ``CLASS_A_DUPLICATES``
    is exactly represented among the members; Class C iff a corresponding
    pair appears in ``CLASS_C_CURATED_PAIRS``; otherwise Class B (sentinel
    placeholder) or unclassified (returned as Class C with the deferred
    note - the unclassified case is treated as Class C for reporting only).
    """
    if full in SENTINEL_FULL_PLACEHOLDERS:
        return "B", "sentinel-placeholder full (60 affected rows skiplisted)"
    pids = {r.get("party_id") for r in members}
    for delete_pid, keep_pid in CLASS_A_DUPLICATES:
        if delete_pid in pids and keep_pid in pids:
            return "A", f"PR #952 self-duplicate; keep {keep_pid}, delete {delete_pid}"
    for delete_pid, keep_pid in CLASS_C_CURATED_PAIRS.items():
        if delete_pid in pids and keep_pid in pids:
            return "C", f"curated dual-spelling; keep {keep_pid}, delete {delete_pid}"
    return "C", "legit dual-spelling; defer to Hans+Max party-lineage review"



"""Dedupe ``parties.csv`` self-duplicates and legit dual-spelling pairs (PR-Q1 / PR-Q1b).

Run from the repo root:

    python -m tools.dedupe_parties_csv                      # dry-run (Class A only)
    python -m tools.dedupe_parties_csv --apply              # merge Class A
    python -m tools.dedupe_parties_csv --include-class-c    # dry-run (A + C)
    python -m tools.dedupe_parties_csv --include-class-c --apply  # merge A + C

Background
----------

The PR #952 correlator (2026-06-09) minted NEW ``parties.csv`` rows for
publisher labels that already had a row carrying the same ``full`` value,
producing same-``full``-different-``party_id`` pairs that the central
resolver cannot tell apart. PR-Q1 commit 2 adds a ``full``-name fallback
to ``party_resolver.load_resolver``; that fallback's collision-set rule
WOULD silently drop these duplicates from the by_alias index unless the
collisions are cleaned up first. This tool is commit 1 of PR-Q1: it merges
the PR #952 self-dupes into the pre-existing canonical rows and rewrites
every ``party_id`` FK across the corpus.

Collision-set classification
----------------------------

Audit of ``datasets/data/entities/parties.csv`` (2026-06-11) found 11
distinct ``full`` values appearing in more than one non-sentinel row. They
fall into three classes:

  - Class A (PR #952 self-duplicates) - the curator-confirmed pairs in
    ``CLASS_A_DUPLICATES`` below. The tool merges these into the canonical
    row and deletes the duplicate. Per the Fowler tiebreaker rule
    (`pick the row whose ``short`` is shorter; on tie, prefer the row
    without dashes/spaces; on tie, prefer the row with more aliases /
    older-looking party_id`), the canonical is the SHORTER, NO-DASH row.

  - Class B (sentinel-placeholder ``full`` values: ``NA'S`` /
    ``EXPANDED PARTY NAME NOT RELEASED BY THE ECI`` / ``UNKNOWN PARTY``).
    These are NOT identity collisions; they are 60 distinct parties whose
    ``full`` was never recorded by the publisher and got back-filled with a
    sentinel string. The tool LEAVES them alone; the resolver's
    ``_SENTINEL_FULL_PLACEHOLDERS`` skiplist (commit 2) keeps them out of
    the by_alias index so they never collide.

  - Class C (legitimate dual-spelling collisions: AJSU/AJSUP, JJP/JNJP,
    RLP/RALTP, ICSP/ICP, SKPP/SRPP, AD(S)/ADAL). PR-Q1b (2026-06-12)
    adds the ``CLASS_C_CURATED_PAIRS`` map and the ``--include-class-c``
    CLI flag so the tool merges these pairs too when invoked with the
    flag. The canonical pid in each pair is chosen with an EXTRA
    preference for the ECI-standard short over the publisher variant
    (e.g. AD(S) over ADAL, AJSU over AJSUP); see the inline comments on
    ``CLASS_C_CURATED_PAIRS`` for the per-pair rationale. Unlike Class A,
    the Fowler tiebreaker cross-check does NOT run on Class C - the
    curator pick reflects ECI-domain knowledge (publisher abbreviation
    standards) that the algorithm does not encode.

Ordering note (dedupe <-> correlate_unk_apply)
-----------------------------------------------

A ``verdict.csv`` generated by this tool BEFORE a fresh dedupe run may
list a ``delete_pid`` that has already been removed. The follow-on
``tools.correlate_unk_apply`` reader skips any row whose ``delete_pid``
is not present in the current parties.csv (logged, not raised); re-running
this tool to regenerate the verdict ahead of correlate_unk_apply is the
recommended hygiene step.
"""

